export function resolveLanguageCode(raw?: string): SupportedLanguage {
  if (!raw) return 'en';
  const clean = raw.toLowerCase().trim();
  if (clean === 'en' || clean.startsWith('en-') || clean.includes('english')) return 'en';
  if (clean === 'es' || clean.startsWith('es-') || clean.includes('spanish') || clean.includes('español')) return 'es';
  if (clean === 'fr' || clean.startsWith('fr-') || clean.includes('french') || clean.includes('français')) return 'fr';
  if (clean === 'de' || clean.startsWith('de-') || clean.includes('german') || clean.includes('deutsch')) return 'de';
  if (clean === 'ja' || clean.startsWith('ja-') || clean.includes('japanese') || clean.includes('日本語')) return 'ja';
  if (clean === 'it' || clean.startsWith('it-') || clean.includes('italian') || clean.includes('italiano')) return 'it';
  if (clean === 'pt' || clean.startsWith('pt-') || clean.includes('portuguese') || clean.includes('português')) return 'pt';
  return 'en';
}

export function translate(key: string, langInput?: string): string {
  const lang = resolveLanguageCode(langInput);
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
}

export function useTranslation(langInput?: string) {
  const currentLang = resolveLanguageCode(langInput);

  return useMemo(() => {
    const t = (key: string, fallback?: string): string => {
      const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
      return dict[key] || TRANSLATIONS.en[key] || fallback || key;
    };

    return {
      t,
      currentLang,
      isRTL: false,
    };
  }, [currentLang]);
}
